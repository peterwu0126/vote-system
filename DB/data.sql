USE vote_system;

-- ---------------------------------------------------------------------
-- 投票項目 (voting_item)
-- ---------------------------------------------------------------------
INSERT INTO voting_item (item_id, item_name, vote_count) VALUES
    (1, '電腦', 0),
    (2, '滑鼠', 0);

-- ---------------------------------------------------------------------
-- 投票紀錄 (voting_record)
-- 使用 Stored Procedure 寫入，確保 vote_count 同步累加
-- ---------------------------------------------------------------------
CALL sp_vote_cast('Leo',   1);
CALL sp_vote_cast('Sandy', 1);
CALL sp_vote_cast('Sandy', 2);
CALL sp_vote_cast('Randy', 2);
CALL sp_vote_cast('RSY',   2);

-- 額外補一筆項目，方便測試新增/編輯/刪除功能
CALL sp_item_create('鍵盤', @new_id);
